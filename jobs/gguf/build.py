def prepare_public_tree(
    contract: Mapping[str, object],
    output_dir: Path,
    base_dir: Path,
    final_gguf: Path,
    build_manifest: Mapping[str, object],
    validation_manifest: Mapping[str, object],
) -> dict[str, str]:
    """Create the exact allowlisted Hub upload tree and both hash manifests."""
    public_dir = output_dir / "public"
    gguf_dir = public_dir / "gguf"
    gguf_dir.mkdir(parents=True, mode=0o750)
    artifact_path = public_dir / contract["artifact"]["path"]
    final_gguf.rename(artifact_path)
    shutil.copyfile(base_dir / "LICENSE", gguf_dir / "QWEN3-1.7B-LICENSE.txt")
    common.write_manifest(gguf_dir / "build.json", build_manifest)
    common.write_manifest(gguf_dir / "validation.json", validation_manifest)

    gguf_digests = common.hash_tree(gguf_dir)
    common.write_sha256sums(gguf_dir / "SHA256SUMS", gguf_digests)

    artifact = build_manifest["artifact"]
    (public_dir / "README.md").write_text(
        render_model_card(contract, artifact),
        encoding="utf-8",
    )
    (public_dir / "THIRD_PARTY_NOTICES.md").write_text(
        render_third_party_notices(contract),
        encoding="utf-8",
    )
    common.write_manifest(
        public_dir / "publication.json",
        {
            "schema_version": 1,
            "target_release": contract["artifact"]["release"],
            "repository": contract["artifact"]["repository"],
            "expected_parent_revision": contract["artifact"]["expected_parent_revision"],
            "base_model": {
                "id": contract["base_model"]["id"],
                "revision": contract["base_model"]["revision"],
                "license": contract["base_model"]["license"],
            },
            "adapter_revision": contract["adapter"]["revision"],
            "artifact": artifact,
            "experimental": True,
            "signed": False,
        },
    )
    root_digests = dict(contract["publication"]["inherited_files"])
    root_digests.update(common.hash_tree(public_dir))
    root_digests.pop("SHA256SUMS", None)
    common.write_sha256sums(public_dir / "SHA256SUMS", root_digests)

    actual_files = set(common.hash_tree(public_dir))
    allowed_files = set(contract["publication"]["allowed_files"])
    if actual_files != allowed_files:
        raise RuntimeError(
            "public upload tree does not match allowlist; "
            f"actual={sorted(actual_files)}, allowed={sorted(allowed_files)}"
        )
    return common.hash_tree(public_dir)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    validate_no_build_token()
    common.prepare_output_dir(args.output_dir)
    started_at = time.monotonic()
    contract = common.load_contract()
    hardware = validate_cuda_runtime()

    private_dir = args.output_dir / "private"
    merged_dir = private_dir / "merged"
    toolchain_dir = private_dir / "toolchain"
    private_dir.mkdir(mode=0o750)
    toolchain_dir.mkdir(mode=0o750)

    base_dir, adapter_dir = download_inputs(contract)
    rendered_prompt, hf_validation = merge_adapter(
        contract,
        base_dir,
        adapter_dir,
        merged_dir,
        private_dir,
    )
    converter, quantizer, cli = prepare_llama_cpp(contract, toolchain_dir)
    bf16_path = private_dir / "codegeist-llm-BF16.gguf"
    final_path = private_dir / "codegeist-llm-Q4_K_M.gguf"

    conversion_environment = dict(os.environ)
    conversion_environment.pop("HF_TOKEN", None)
    conversion_environment["HF_HUB_DISABLE_IMPLICIT_TOKEN"] = "1"
    conversion_environment["UV_PROJECT_ENVIRONMENT"] = (
        "/tmp/codegeist-gguf-conversion-venv"
    )
    conversion = conversion_command(converter, merged_dir, bf16_path)
    _run_logged(
        conversion,
        private_dir / "conversion.log",
        conversion_environment,
    )
    validate_gguf(bf16_path)

    quantization = quantization_command(
        quantizer,
        bf16_path,
        final_path,
        contract,
    )
    _run_logged(quantization, private_dir / "quantization.log")
    validate_gguf(final_path)

    # The quantizer has successfully loaded every BF16 GGUF tensor before
    # producing Q4_K_M. Behavioral BF16 equivalence is already checked on the
    # clean-reloaded merged Safetensors model; CPU-only BF16 generation with the
    # official release binary is prohibitively slow and is not the target Docker
    # Model Runner artifact.
    bf16_validation = {
        "gguf_header": True,
        "loaded_by_quantizer": True,
        "behavior_reference": "clean merged BF16 Safetensors",
    }
    q4_validation = run_llama_evaluation(
        cli,
        final_path,
        rendered_prompt,
        contract,
        private_dir / "q4-inference.log",
    )
    all_matches = (
        hf_validation["adapter"]["normalized_match"]
        and hf_validation["merged"]["normalized_match"]
        and q4_validation["normalized_match"]
    )
    artifact_digest = common.hash_file(final_path)
    artifact_size = final_path.stat().st_size
    created_at = datetime.now(timezone.utc).isoformat()
    build_manifest = {
        "schema_version": 1,
        "result": "passed" if all_matches else "evaluation_failed",
        "created_at": created_at,
        "duration_seconds": round(time.monotonic() - started_at, 3),
        "artifact": {
            "path": contract["artifact"]["path"],
            "quantization": contract["artifact"]["quantization"],
            "importance_matrix": None,
            "chat_template": contract["artifact"]["chat_template"],
            "size_bytes": artifact_size,
            "sha256": artifact_digest,
        },
        "inputs": {
            "base_model": {
                "id": contract["base_model"]["id"],
                "revision": contract["base_model"]["revision"],
            },
            "adapter": {
                "id": contract["adapter"]["id"],
                "revision": contract["adapter"]["revision"],
                "weight_sha256": contract["adapter"]["files"][
                    "adapter_model.safetensors"
                ],
            },
        },
        "toolchain": contract["toolchain"],
        "runtime": {
            "python": sys.version.split()[0],
            "hardware": hardware,
            "packages": package_versions(),
        },
        "source_sha256": source_digests(),
        "commands": {
            "conversion": conversion,
            "quantization": quantization,
        },
    }
    validation_manifest = {
        "schema_version": 1,
        "result": "passed" if all_matches else "evaluation_failed",
        "prompt": contract["evaluation"]["prompt"],
        "expected_response": contract["evaluation"]["expected_response"],
        "normalization": contract["evaluation"]["normalization"],
        "thinking": False,
        "stages": {
            **hf_validation,
            "bf16_gguf": bf16_validation,
            "q4_k_m_gguf": q4_validation,
        },
    }
    public_digests = prepare_public_tree(
        contract,
        args.output_dir,
        base_dir,
        final_path,
        build_manifest,
        validation_manifest,
    )
    result_manifest = {
        "schema_version": 1,
        "result": build_manifest["result"],
        "created_at": created_at,
        "artifact": build_manifest["artifact"],
        "public_sha256": public_digests,
    }
    common.write_manifest(args.output_dir / "run.json", result_manifest)
    if all_matches:
        shutil.rmtree(merged_dir)
        bf16_path.unlink()
        shutil.rmtree(toolchain_dir)
    print(common.serialize_manifest(result_manifest), end="")
    if not all_matches:
        raise RuntimeError("one or more transformation stages changed the response")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
