#!/usr/bin/env python3
"""Build the complete experimental Codegeist Q4_K_M GGUF.

The builder is deliberately token-free. It downloads the immutable public base
model and adapter, verifies every source byte, merges PEFT on CUDA in BF16,
clean-reloads Safetensors, converts with pinned llama.cpp source, quantizes once,
and prepares a reviewed Hub upload tree under a unique `/outputs` child.

Heavy ML imports remain inside runtime functions so `tests/test_contract.py` can
validate the build contract without importing PyTorch or downloading weights.
The generated GGUF and intermediates stay outside Git.
"""

